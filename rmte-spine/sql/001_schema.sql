-- RMTE spine — governed Risk / Metric / Test / Evaluation catalog.
-- One database, many archetypes. JSON authoring files are ingested here;
-- Agent 5, Squad 3, and later archetypes all read this catalog.
-- JSONB holds the full HLA row; indexed columns are what every consumer joins on.

CREATE TABLE IF NOT EXISTS archetypes (
    id              TEXT PRIMARY KEY,
    display_name    TEXT NOT NULL,
    pattern_field   TEXT NOT NULL,
    notes           TEXT
);

CREATE TABLE IF NOT EXISTS library_releases (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    archetype_id        TEXT NOT NULL REFERENCES archetypes(id),
    version             TEXT NOT NULL,
    library_id          TEXT NOT NULL,
    status              TEXT NOT NULL DEFAULT 'published',
    source              TEXT,
    notes               JSONB NOT NULL DEFAULT '{}'::jsonb,
    execution_patterns  JSONB NOT NULL DEFAULT '[]'::jsonb,
    family_observation_stage JSONB NOT NULL DEFAULT '{}'::jsonb,
    family_product_layer JSONB NOT NULL DEFAULT '{}'::jsonb,
    metric_observation_stage_overrides JSONB NOT NULL DEFAULT '{}'::jsonb,
    content_hash        TEXT NOT NULL,
    published_at        TIMESTAMPTZ,
    UNIQUE (archetype_id, version)
);

CREATE TABLE IF NOT EXISTS authoring_documents (
    release_id      INTEGER NOT NULL REFERENCES library_releases(id) ON DELETE CASCADE,
    kind            TEXT NOT NULL,
    library_id      TEXT,
    body            JSONB NOT NULL,
    content_hash    TEXT NOT NULL,
    source_sha256   TEXT,
    source_path     TEXT,
    PRIMARY KEY (release_id, kind)
);

CREATE TABLE IF NOT EXISTS metrics (
    release_id                  INTEGER NOT NULL REFERENCES library_releases(id) ON DELETE CASCADE,
    metric_id                   TEXT NOT NULL,
    name                        TEXT NOT NULL,
    family                      TEXT NOT NULL,
    category                    TEXT,
    pillar                      TEXT,
    primary_trust_attribute     TEXT,
    formula                     TEXT,
    test_suite_id               TEXT,
    gate                        TEXT,
    priority                    TEXT,
    severity                    TEXT,
    design_mode                 TEXT,
    body                        JSONB NOT NULL,
    PRIMARY KEY (release_id, metric_id)
);

CREATE TABLE IF NOT EXISTS risks (
    release_id      INTEGER NOT NULL REFERENCES library_releases(id) ON DELETE CASCADE,
    risk_id         TEXT NOT NULL,
    name            TEXT NOT NULL,
    category        TEXT,
    pillar          TEXT,
    trust_attribute TEXT,
    severity        TEXT,
    body            JSONB NOT NULL,
    PRIMARY KEY (release_id, risk_id)
);

CREATE TABLE IF NOT EXISTS risk_metric_links (
    release_id  INTEGER NOT NULL REFERENCES library_releases(id) ON DELETE CASCADE,
    risk_id     TEXT NOT NULL,
    metric_id   TEXT NOT NULL,
    PRIMARY KEY (release_id, risk_id, metric_id)
);

CREATE TABLE IF NOT EXISTS formula_terms (
    release_id          INTEGER NOT NULL REFERENCES library_releases(id) ON DELETE CASCADE,
    metric_id           TEXT NOT NULL,
    term                TEXT NOT NULL,
    meaning             TEXT,
    source_type         TEXT,
    log_or_dataset      TEXT,
    ai_product_layer    TEXT,
    platform_layer      TEXT,
    notes               TEXT,
    body                JSONB NOT NULL,
    PRIMARY KEY (release_id, metric_id, term)
);

CREATE TABLE IF NOT EXISTS product_layers (
    release_id              INTEGER NOT NULL REFERENCES library_releases(id) ON DELETE CASCADE,
    layer_index             INTEGER NOT NULL,
    layer                   TEXT NOT NULL,
    architecture            TEXT,
    logs_telemetry          TEXT,
    key_fields              TEXT,
    ingested_by             TEXT,
    related_metric_families JSONB,
    notes                   TEXT,
    body                    JSONB NOT NULL,
    PRIMARY KEY (release_id, layer_index)
);

CREATE TABLE IF NOT EXISTS family_pattern_notes (
    release_id  INTEGER NOT NULL REFERENCES library_releases(id) ON DELETE CASCADE,
    family      TEXT NOT NULL,
    pattern     TEXT NOT NULL,
    note        TEXT NOT NULL,
    PRIMARY KEY (release_id, family, pattern)
);

CREATE TABLE IF NOT EXISTS metric_pattern_notes (
    release_id  INTEGER NOT NULL REFERENCES library_releases(id) ON DELETE CASCADE,
    metric_id   TEXT NOT NULL,
    pattern     TEXT NOT NULL,
    note        TEXT NOT NULL,
    PRIMARY KEY (release_id, metric_id, pattern)
);

CREATE TABLE IF NOT EXISTS derived_perspectives (
    release_id  INTEGER NOT NULL REFERENCES library_releases(id) ON DELETE CASCADE,
    ordinal     INTEGER NOT NULL,
    body        JSONB NOT NULL,
    PRIMARY KEY (release_id, ordinal)
);

CREATE TABLE IF NOT EXISTS rmte_rows (
    release_id          INTEGER NOT NULL REFERENCES library_releases(id) ON DELETE CASCADE,
    ordinal             INTEGER NOT NULL,
    metric_id           TEXT,
    risk_id             TEXT,
    test_suite_id       TEXT,
    trust_attribute     TEXT,
    pillar              TEXT,
    body                JSONB NOT NULL,
    PRIMARY KEY (release_id, ordinal)
);

CREATE TABLE IF NOT EXISTS catalog_documents (
    kind            TEXT PRIMARY KEY,
    library_id      TEXT,
    body            JSONB NOT NULL,
    content_hash    TEXT NOT NULL,
    source_path     TEXT
);

CREATE INDEX IF NOT EXISTS metrics_family_idx ON metrics (release_id, family);
CREATE INDEX IF NOT EXISTS metrics_trust_idx ON metrics (release_id, primary_trust_attribute);
CREATE INDEX IF NOT EXISTS formula_terms_term_idx ON formula_terms (release_id, term);
CREATE INDEX IF NOT EXISTS risk_metric_links_metric_idx ON risk_metric_links (release_id, metric_id);
CREATE INDEX IF NOT EXISTS rmte_rows_metric_idx ON rmte_rows (release_id, metric_id);
CREATE INDEX IF NOT EXISTS rmte_rows_risk_idx ON rmte_rows (release_id, risk_id);
